public class index {
    public static void main(String[] args) {
        double l = 5; // length
        double b = 3; // breadth
        double h = 4; // height
        double tsa = 2 * (l * b + b * h + l * h); // formula for total surface area of cuboid
        System.out.println("Total Surface Area of Cuboid : " + tsa);
    } 
}
